"""Token usage ledger.

Every LLM/vision call anywhere in the pipeline must log through this module.
The ledger is an append-only CSV so partial runs are never lost, and a final
consolidated report is generated by `write_usage_report()`.
"""

from __future__ import annotations

import csv
import threading
from datetime import datetime, timezone
from pathlib import Path
from typing import Any

from code.config import EVALUATION_DIR, TOKEN_LEDGER_CSV, MODEL_COSTS_PER_1M

_LOCK = threading.Lock()

_FIELDNAMES = [
    "timestamp", "provider", "model", "call_kind", "request_id",
    "input_tokens", "output_tokens", "estimated_cost_usd", "notes",
]


def _ensure_dirs() -> None:
    EVALUATION_DIR.mkdir(parents=True, exist_ok=True)


def _estimate_cost(model: str, input_tokens: int, output_tokens: int) -> float:
    in_cost, out_cost = MODEL_COSTS_PER_1M.get(model, (0.0, 0.0))
    return (input_tokens * in_cost + output_tokens * out_cost) / 1_000_000.0


def record(
    provider: str,
    model: str,
    input_tokens: int = 0,
    output_tokens: int = 0,
    call_kind: str = "llm",
    request_id: str = "",
    notes: str = "",
) -> dict[str, Any]:
    """Append one usage row. Safe to call from anywhere in the pipeline."""
    in_tok = int(input_tokens)
    out_tok = int(output_tokens)
    cost = _estimate_cost(model, in_tok, out_tok)
    row = {
        "timestamp": datetime.now(timezone.utc).isoformat(timespec="seconds"),
        "provider": provider,
        "model": model,
        "call_kind": call_kind,
        "request_id": request_id,
        "input_tokens": in_tok,
        "output_tokens": out_tok,
        "estimated_cost_usd": f"{cost:.8f}",
        "notes": notes,
    }
    with _LOCK:
        _ensure_dirs()
        exists = TOKEN_LEDGER_CSV.exists()
        with TOKEN_LEDGER_CSV.open("a", newline="", encoding="utf-8") as f:
            writer = csv.DictWriter(f, fieldnames=_FIELDNAMES)
            if not exists:
                writer.writeheader()
            writer.writerow(row)
    return row


def records() -> list[dict[str, Any]]:
    """Read back every recorded row."""
    _ensure_dirs()
    if not TOKEN_LEDGER_CSV.exists():
        return []
    with TOKEN_LEDGER_CSV.open(newline="", encoding="utf-8") as f:
        return list(csv.DictReader(f))


def totals() -> dict[str, Any]:
    """Aggregate totals across the ledger."""
    rows = records()
    in_tok = sum(int(r["input_tokens"]) for r in rows)
    out_tok = sum(int(r["output_tokens"]) for r in rows)
    cost = sum(float(r["estimated_cost_usd"]) for r in rows)
    by_model: dict[str, dict[str, Any]] = {}
    for r in rows:
        key = f"{r['provider']}:{r['model']}"
        agg = by_model.setdefault(key, {
            "provider": r["provider"], "model": r["model"],
            "calls": 0, "input_tokens": 0, "output_tokens": 0,
            "cost_usd": 0.0,
        })
        agg["calls"] += 1
        agg["input_tokens"] += int(r["input_tokens"])
        agg["output_tokens"] += int(r["output_tokens"])
        agg["cost_usd"] += float(r["estimated_cost_usd"])
    return {
        "calls": len(rows),
        "input_tokens": in_tok,
        "output_tokens": out_tok,
        "total_tokens": in_tok + out_tok,
        "estimated_cost_usd": cost,
        "by_model": by_model,
    }


def write_usage_report(path: Path | None = None) -> Path:
    """Write evaluation/usage_report.md from everything logged so far."""
    path = path or (EVALUATION_DIR / "usage_report.md")
    t = totals()
    lines = [
        "# Token Usage Report",
        "",
        f"Generated: {datetime.now(timezone.utc).isoformat(timespec='seconds')}",
        "",
        "## Overall",
        "",
        f"- Model calls: {t['calls']}",
        f"- Input tokens: {t['input_tokens']:,}",
        f"- Output tokens: {t['output_tokens']:,}",
        f"- Total tokens: {t['total_tokens']:,}",
        f"- Estimated total cost: ${t['estimated_cost_usd']:.4f}",
        "",
        "## Per Model",
        "",
        "| Provider | Model | Calls | Input Tokens | Output Tokens | Est. Cost (USD) |",
        "|---|---|---:|---:|---:|---:|",
    ]
    for m in t["by_model"].values():
        lines.append(
            f"| {m['provider']} | {m['model']} | {m['calls']} | "
            f"{m['input_tokens']:,} | {m['output_tokens']:,} | ${m['cost_usd']:.4f} |"
        )
    _ensure_dirs()
    path.write_text("\n".join(lines) + "\n", encoding="utf-8")
    return path
